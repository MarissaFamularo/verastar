// Bundle the app modules the digest-run edge function needs into one file so the deploy
// never depends on relative imports reaching outside supabase/functions. npm packages stay
// external and resolve through supabase/functions/deno.json on Deno.
import { build } from 'esbuild'

await build({
  entryPoints: ['supabase/functions/digest-run/app.entry.js'],
  // Served by Netlify with the frontend; the digest-run function imports it by URL at cold
  // start, so a deploy of main is a deploy of the server's app code too.
  outfile: 'public/server/app.bundle.js',
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'esnext',
  external: ['@anthropic-ai/sdk', '@supabase/supabase-js', 'linkedom', 'pdfjs-dist', 'pdfjs-dist/*'],
  logLevel: 'info',
  minify: true,
  legalComments: 'none',
  banner: { js: '// GENERATED by scripts/bundle-functions.mjs — do not edit. Rebuild: npm run bundle:functions' },
})

// Deno resolves bare specifiers through an import map, which does not reach a module
// loaded by URL. Rewrite the externals to explicit npm: specifiers so the bundle is
// self-describing wherever it is loaded from.
import { readFileSync, writeFileSync } from 'node:fs'
const out = 'public/server/app.bundle.js'
let js = readFileSync(out, 'utf8')
js = js.replace(/from"@anthropic-ai\/sdk"/g, 'from"npm:@anthropic-ai/sdk@0.110.0"')
js = js.replace(/from"@supabase\/supabase-js"/g, 'from"npm:@supabase/supabase-js@2"')
writeFileSync(out, js)
