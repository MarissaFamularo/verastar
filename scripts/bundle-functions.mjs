// Bundle the app modules the digest-run edge function needs into one file that is deployed
// WITH the function (supabase/functions/digest-run/app.bundle.js, imported relatively), so
// the scheduler runs exactly the reviewed local source: no remote URL, no commit pin.
// npm packages stay external and resolve as explicit npm: specifiers on Deno.
//
// Also writes app.bundle.manifest.js: the bundle's sha256, a sha256 of every source file
// that went into it, and the extraction/verification versions and model ids the bundle
// carries. The source sha256 is also compiled INTO the bundle (BUNDLE_SOURCE_SHA256), so
// at cold start digest-run/index.ts can check that the bundle it loaded was built from the
// source set its manifest names, with the same versions and models. That is source-set
// identity, not byte identity: the deployed bytes are compared with the manifest's
// bundleSha256 offline (scripts/check-spending-contract.mjs) and, at release, against the
// downloaded deployed function (docs/SPENDING_CONTRACT.md § Cutover).
import { build } from 'esbuild'
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'

export const BUNDLE_OUT = 'supabase/functions/digest-run/app.bundle.js'
export const MANIFEST_OUT = 'supabase/functions/digest-run/app.bundle.manifest.js'
export const BUNDLE_ENTRY = 'supabase/functions/digest-run/app.entry.js'

const sha256 = (buf) => createHash('sha256').update(buf).digest('hex')

const buildOptions = (define = {}) => ({
  entryPoints: [BUNDLE_ENTRY],
  bundle: true,
  write: false,
  metafile: true,
  format: 'esm',
  platform: 'neutral',
  target: 'esnext',
  external: ['@anthropic-ai/sdk', '@supabase/supabase-js', 'linkedom', 'pdfjs-dist', 'pdfjs-dist/*'],
  logLevel: 'warning',
  minify: true,
  legalComments: 'none',
  outfile: BUNDLE_OUT,
  banner: { js: '// GENERATED by scripts/bundle-functions.mjs — do not edit. Rebuild: npm run bundle:functions' },
  define,
})

export async function bundleFunctions({ write = true } = {}) {
  // Pass 1 finds the inputs; pass 2 compiles their combined hash into the bundle.
  const firstPass = await build(buildOptions({ __VERASTAR_BUNDLE_SOURCE_SHA256__: 'null' }))
  const inputs = Object.keys(firstPass.metafile.inputs).sort()
  const inputHashes = Object.fromEntries(inputs.map((p) => [p, sha256(readFileSync(p))]))
  const sourceSha256 = sha256(inputs.map((p) => `${p}\0${inputHashes[p]}\n`).join(''))
  const result = await build(buildOptions({ __VERASTAR_BUNDLE_SOURCE_SHA256__: JSON.stringify(sourceSha256) }))
  if (JSON.stringify(Object.keys(result.metafile.inputs).sort()) !== JSON.stringify(inputs)) throw new Error('bundle inputs changed between passes')
  const bare = new TextDecoder().decode(result.outputFiles[0].contents)
  // Deno resolves bare specifiers through an import map only for local modules it can see;
  // explicit npm: specifiers keep the bundle self-describing.
  const js = bare
    .replace(/from"@anthropic-ai\/sdk"/g, 'from"npm:@anthropic-ai/sdk@0.110.0"')
    .replace(/from"@supabase\/supabase-js"/g, 'from"npm:@supabase/supabase-js@2"')

  // Versions and models come from the bundle itself, evaluated in Node against the same
  // npm packages, so the manifest cannot drift from what the bundle carries.
  mkdirSync('node_modules/.cache', { recursive: true })
  const probe = `node_modules/.cache/verastar-app-bundle-${process.pid}.mjs`
  writeFileSync(probe, bare)
  let app
  try {
    app = await import(pathToFileURL(probe).href)
  } finally {
    rmSync(probe, { force: true })
  }
  if (app.BUNDLE_SOURCE_SHA256 !== sourceSha256) throw new Error('source hash was not compiled into the bundle')
  const manifest = {
    bundleSha256: sha256(js),
    sourceSha256,
    extractionVersion: app.CURRENT_EXTRACTION_VERSION,
    verificationVersion: app.VERIFICATION_VERSION,
    models: { ...app.MODELS },
    anthropicSdk: '0.110.0',
    inputs: inputHashes,
  }
  if (write) {
    writeFileSync(BUNDLE_OUT, js)
    writeFileSync(MANIFEST_OUT, `// GENERATED by scripts/bundle-functions.mjs — do not edit.\nexport default ${JSON.stringify(manifest, null, 2)}\n`)
  }
  return { js, manifest }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { manifest } = await bundleFunctions()
  console.log(`${BUNDLE_OUT}  sha256 ${manifest.bundleSha256}`)
  console.log(`source sha256 ${manifest.sourceSha256} (${Object.keys(manifest.inputs).length} files)`)
  console.log(`extraction ${manifest.extractionVersion}  verification ${manifest.verificationVersion}`)
  console.log(`models ${JSON.stringify(manifest.models)}`)
}
